"""Numerical regression against main 536114a with its pinned Rikka fd486f6.

The fixture was generated by the unmodified main DefaultRikkaStrategy and its
actual pinned dependency, using the deterministic sensor input below.
"""

from __future__ import annotations

import json
from io import BytesIO
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pytest
from rikka.analysis_api import list_methods

from src.registry.catalog import pipeline_from_method
from src.registry.rikka_executor import RikkaComponentExecutor

GOLDEN = json.loads(
    (Path(__file__).parent / "fixtures/legacy-pdr-main-536114a.json").read_text()
)


@pytest.mark.parametrize("case", GOLDEN["cases"], ids=lambda case: case["name"])
def test_main_csv_coordinates_direction_and_time_origin(case: dict[str, Any]) -> None:
    t = np.arange(0, 8, 0.01)
    acce = pd.DataFrame(
        {
            "t": t,
            "x": 0.15 * np.sin(t),
            "y": np.zeros(len(t)),
            "z": 9.81 + 2.5 * np.sin(2 * np.pi * 1.8 * t),
        }
    )
    gyro = pd.DataFrame(
        {
            "t": t,
            "x": np.zeros(len(t)),
            "y": np.zeros(len(t)),
            "z": np.zeros(len(t)),
        }
    )
    inputs = {
        "acce": acce.to_csv(index=False).encode(),
        "gyro": gyro.to_csv(index=False).encode(),
        "metadata": b'{"recording_start_wall_time_ms":0}',
    }
    component = pipeline_from_method(
        next(method for method in list_methods() if method.method_id == "pdr")
    ).components[0]
    output = RikkaComponentExecutor().execute(
        component, inputs, {**case["parameters"], "_legacy_trajectory": True}
    )["trajectory"]
    actual = pd.read_csv(BytesIO(output["_legacy_csv"]))
    expected = pd.DataFrame(
        case["expected"]["data"], columns=case["expected"]["columns"], dtype=float
    )
    assert list(actual.columns) == list(expected.columns)
    np.testing.assert_allclose(
        actual.to_numpy(), expected.to_numpy(), rtol=1e-9, atol=1e-9, equal_nan=True
    )
    assert len(actual) > 1
    assert actual.rikka_timestamp_s.iloc[1] == 0
